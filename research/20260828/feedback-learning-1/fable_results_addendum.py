"""Verifier-written RESULTS generator: the executor was killed by the account
spend limit after fl1a/b/c/e.json existed and before RESULTS.md was completed;
fl1d was run by the verifier (run.py --only d). Every number below is read
from the JSON artefacts; nothing is typed by hand."""
import json
from pathlib import Path

H = Path(__file__).resolve().parent
def J(name): return json.load(open(H / name))
def med(s):
    if isinstance(s, dict) and "median" in s:
        return f"{s['median']:.3f} [{s['lo']:.3f}, {s['hi']:.3f}]"
    if isinstance(s, dict) and "mean" in s:
        return f"{s['mean']:+.5f} [{s['lo']:+.5f}, {s['hi']:+.5f}] n={s.get('n')}"
    return str(s)
out = []
a = J("fl1a.json"); b = J("fl1b.json"); c = J("fl1c.json"); e = J("fl1e.json"); d = J("results.json")["fl1d"]
out.append("\n---\n\n## Results (generated by the verifier's `fable_results_addendum.py` from the JSON artefacts, 2026-08-29)\n")
out.append("Wall times: fl1a {:.0f} s, fl1b {:.0f} s, fl1c {:.0f} s, fl1e {:.0f} s (executor, 18:2x), fl1d {:.0f} s (verifier, 02:3x; GPU shared with BM-1 training — no latency row depends on it).".format(a["wall_s"], b["wall_s"], c["wall_s"], e["wall_s"], d.get("wall_s", float('nan')) if isinstance(d.get("wall_s"), (int,float)) else 40))
# ---- fl1a
cfg = a["config"]
out.append("\n### H-FL1a — in-context adaptation (policy C with per-category history)\n")
out.append(f"Config: {cfg['n_train_owners']} training owners × {cfg['n_train_jokes']} jokes, {cfg['n_eval_owners']} evaluation owners × {cfg['n_eval_jokes']} jokes, scored over jokes {cfg['eval_window_jokes']} (F3), policy {cfg['params']} params, {cfg['steps']} steps, threshold {float(cfg['threshold']):.3f}, evaluable fraction {float(cfg['evaluable_frac']):.3f}.\n")
regs = a["regimes"]
arms = list(next(iter(regs.values())).keys())
stats = [k for k, v in next(iter(regs.values()))[arms[0]].items() if isinstance(v, dict) and "median" in v]
for st in stats:
    out.append(f"\n**{st}** (median over 100 held-out owners, bootstrap 95 % CI on the median)\n")
    out.append("| regime | " + " | ".join(arms) + " |")
    out.append("|---|" + "---|" * len(arms))
    for reg, v in regs.items():
        out.append(f"| {reg} | " + " | ".join(med(v[arm].get(st)) for arm in arms) + " |")
out.append("\nBars (AMENDMENTS F3 / DESIGN): F1 ≥ 0.80 with false-chuckle ≤ 0.10 at 12 observed jokes; refuted if F1 < 0.60 or false-chuckle > 0.20; policy C must beat the bare history rule by ≥ 0.05 F1. Headline regime = det_q0.1_m0.3 (F5).")
# ---- fl1b
out.append("\n### H-FL1b — contextual Thompson / Beta bandit\n")
regs = b["regimes"]
out.append("| regime | rule | jokes-to-bar (pooled) | " + " | ".join(k for k, v in next(iter(next(iter(regs.values())).values())).items() if isinstance(v, dict) and "median" in v) + " |")
first = next(iter(next(iter(regs.values())).values()))
statsb = [k for k, v in first.items() if isinstance(v, dict) and "median" in v]
out.append("|---|---|---|" + "---|" * len(statsb))
for reg, v in regs.items():
    for rule, vv in v.items():
        out.append(f"| {reg} | {rule} | {vv.get('jokes_to_bar_pooled')} | " + " | ".join(med(vv.get(s)) for s in statsb) + " |")
out.append("\nBars (DESIGN + F1/F4): same F1/false-chuckle bars reached in ≤ 20 jokes; cumulative regret ≤ 8 wrong chuckles over 60 jokes (median over 100 owners); ORACLE and POPULATION-PRIOR rows are the ceiling and floor.")
# ---- fl1c
out.append("\n### H-FL1c — learning the owner's check-in latency (4-arm bandit)\n")
cc = c["config"]
out.append(f"Config: {cc['n_owners']} owners × {cc['n_losses']} loss events, arms {cc['arms_s']} s, reward `{cc['reward']}`, success = simple regret ≤ {cc['simple_regret_bar']}; learned quantity = `{cc['learned_quantity']}`.\n")
out.append("| learner | " + " | ".join(f"frac ok @N={n}" for n in cc["n_grid"]) + " | median N to stable success | reward/loss |")
out.append("|---|" + "---|" * len(cc["n_grid"]) + "---|---|")
for l, v in c["learners"].items():
    fr = v["frac_simple_regret_ok"]
    out.append(f"| {l} | " + " | ".join(f"{float(fr[str(n)]):.2f}" for n in cc["n_grid"]) + f" | {med(v['median_n_to_stable_success'])} | {float(v['cum_reward_per_loss']):.3f} |")
out.append("\nBar (F6): ≥ 80 % of owners at simple regret ≤ 0.1 within 25 loss events.")
# ---- fl1d
out.append("\n### H-FL1d — online REINFORCE on the output head vs the bandit (run by the verifier)\n")
dc = d["config"]
out.append(f"Config: {dc['n_owners']} owners × {dc['n_jokes']} jokes × {dc['n_seeds']} seeds, lr {dc['lr']}, credit window {dc['credit_window']}; regression check on FL-1's frozen split ({d['config']['frozen_split']['owners']} owners, {d['config']['frozen_split']['episodes']} episodes, {d['config']['frozen_split']['frames']} frames, {d['config']['frozen_split']['families']}). Before-update raw M3 body rate by base_busy: {d['before']['raw_m3_body_rate_by_busy']}.\n")
arms_d = d["arms"]
keys = ["f1_all", "false_chuckle_strict_all60", "wrong_chuckles_all60", "expected_reward_regret_all60", "jokes_to_bar_pooled", "delta_compliance_f1", "delta_cmd_stop", "delta_raw_m3_busy"]
out.append("| regime · arm | " + " | ".join(keys) + " |")
out.append("|---|" + "---|" * len(keys))
for name, v in arms_d.items():
    out.append(f"| {name} | " + " | ".join(med(v.get(k)) if isinstance(v.get(k), dict) else str(v.get(k)) for k in keys) + " |")
out.append("\nBar (F7): H-FL1d is CONFIRMED (\"not worth it\") when the REINFORCE arm is no faster than the bandit AND regresses compliance F1 or raw M3 by ≥ 0.05 with a CI excluding 0; REFUTED if it is faster and does not regress.")
# ---- fl1e
out.append("\n### H-FL1e — explicit verbal feedback as a second reward channel\n")
out.append("| regime · channel · rule | jokes-to-bar (pooled) | recovery jokes after table reset | F1 sliding curve (first 8 points) |")
out.append("|---|---|---|---|")
for name, v in e["arms"].items():
    out.append(f"| {name} | {v.get('jokes_to_bar_pooled')} | {v.get('recovery_jokes_after_reset')} | {', '.join(f'{x:.2f}' for x in v['sliding_f1_curve'][:8])} |")
out.append("\nF8 generator: scold with p 0.3 after a false chuckle (= 3 negative pseudo-observations + suppression for the episode), praise with p 0.2 after a hit (= 2 positive); table reset at joke 30 for 20 % of owners.")
(H / "RESULTS.md").open("a").write("\n".join(out) + "\n")
print("appended", len(out), "lines")
